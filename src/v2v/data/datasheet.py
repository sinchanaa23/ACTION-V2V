"""Dataset datasheet (P1-06). Every number comes from the gold file.

python -m v2v.data.datasheet data/annotated/gold.jsonl data/annotated/exports/*.json
"""

import argparse
from collections import Counter
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

from v2v.contracts import HazardType
from v2v.data.annotate import GoldRecord, kappa_report, load_exports, read_gold


def _table(header: str, counts: Iterable[tuple[str, int]]) -> str:
    rows = "\n".join(f"| {name} | {count} |" for name, count in counts)
    return f"| {header} | Records |\n|---|---|\n{rows}\n"


def render(gold: Sequence[GoldRecord], kappa: dict[str, Any]) -> str:
    """Render the datasheet. Classes with no records are shown as 0."""
    classes = Counter(r.hazard.value for r in gold)
    sources = Counter(r.source for r in gold)
    subsets = [
        ("Negated", sum(r.negated for r in gold)),
        ("Hedged", sum(r.hedged for r in gold)),
        ("No location span", sum(not r.locations for r in gold)),
    ]
    kappas = "\n".join(f"- {key}: {value}" for key, value in sorted(kappa.items()))
    return f"""# Dataset datasheet

Generated by `v2v.data.datasheet`. Do not edit the numbers by hand.

## Motivation
Real informal English and Hinglish driver reports, labelled to train and test
hazard classification for simulated V2V warnings.

## Composition
Total records: {len(gold)}

{_table("Class", [(h.value, classes[h.value]) for h in HazardType])}
{_table("Source", sorted(sources.items()))}
{_table("Hard subset", subsets)}
## Collection
Survey responses from consenting adults, and Reddit and YouTube text through
their official APIs. All text is real and human-written. None is generated,
paraphrased, translated or augmented.

## Privacy
Usernames, phone numbers, plate numbers, emails and URLs are scrubbed before
storage. Survey responses store no names or contact details. Only Reddit and
YouTube IDs may be released, never the raw scraped text.

## Annotation
Labelled in Label Studio using `docs/annotation_guide.md`, with about 20% double
annotated and disagreements settled by P1.

{kappas}

## Known limits
Rule-based scrubbing can miss PII. Keyword-based collection favours reports that
use common hazard words. Respondents and commenters are not a representative
sample of Indian drivers.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("gold", type=Path)
    parser.add_argument("exports", nargs="+", type=Path)
    parser.add_argument("--out", type=Path, default=Path("docs/datasheet.md"))
    args = parser.parse_args()
    text = render(read_gold(args.gold), kappa_report(load_exports(args.exports)))
    args.out.write_text(text, encoding="utf-8")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
